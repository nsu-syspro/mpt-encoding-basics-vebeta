#!/usr/bin/env bash

# Вывести время в формате:
#   13 октября 2023 года, Пятница

export LC_ALL=ru_RU.UTF-8

date -d "$*" '+%d %B %Y года, %A' | sed -E 's/январь/января/;s/февраль/февраля/;s/март/марта/;s/апрель/апреля/;s/май/мая/;s/июнь/июня/;s/июль/июля/;s/август/августа/;s/сентябрь/сентября/;s/октябрь/октября/;s/ноябрь/ноября/;s/декабрь/декабря/;s/, ([а-яё])/, \U\1/'